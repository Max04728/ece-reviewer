// build-drills.mjs — P6: derive practice sets from problem records.
//
// This is the payoff for storing problems as structured data instead of prose: one
// authored record feeds the topic note AND the drill, with no re-typing.
//
//   node build-drills.mjs                     # regenerate drills for every rendered area
//   node build-drills.mjs --area 05_Electromagnetics
//   node build-drills.mjs --per 10             # problems per drill (default 8)
//   node build-drills.mjs --seed 12345         # deterministic shuffle (default 1)
//   node build-drills.mjs --include-traps      # also emit a traps-only recall drill
//
// Output: ECE_Reviewer_Vault/<part>/<area>/Sets/<Area>_Drill.md (+ _Traps.md)
// A drill pools problems from every T1/T2 topic in the area, deterministically
// shuffled so the run is reproducible and re-running does not churn the file.

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { AREAS, VAULT } from './vault.mjs';

const args = process.argv.slice(2);
const flag = (n) => args.includes(`--${n}`);
const opt = (n, d = null) => {
  const i = args.indexOf(`--${n}`);
  return i >= 0 ? args[i + 1] : d;
};

const perDrill = Number(opt('per', 8));
const seed = Number(opt('seed', 1));
const onlyArea = opt('area');
const includeTraps = flag('include-traps');
const today = new Date().toISOString().slice(0, 10);

const payloadPath = (t) => `build/payload/${t.part}/${t.area}/${t.slug}.json`;

/** Deterministic PRNG (mulberry32) so a given seed always yields the same drill. */
function rng(a) {
  return function () {
    a |= 0; a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffle(arr, rand) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

const write = (p, s) => {
  mkdirSync(join(p, '..'), { recursive: true });
  writeFileSync(p, s, 'utf8');
};

/** Replace a MOC's `## Sets & Drills` section with the generated list. */
function linkSetsIntoMOC(areaDir, mocFile, files) {
  if (!existsSync(mocFile)) return false;
  const body = files.length
    ? files
        .map((f) => {
          const base = f.replace(/\.md$/, '');
          return `- [[${base}|${base.replace(/_/g, ' ')}]]`;
        })
        .join('\n')
    : '_None yet._';

  let text = readFileSync(mocFile, 'utf8');
  if (!text.includes('## Sets & Drills')) {
    text = text.trimEnd() + `\n\n## Sets & Drills\n\n<!-- generated by build-drills.mjs -->\n`;
  }
  const re = /## Sets & Drills[^\n]*\n([\s\S]*?)(?=\n## |\n*$)/;
  if (!re.test(text)) return false;
  const next = text.replace(re, `## Sets & Drills\n\n<!-- generated by build-drills.mjs -->\n\n${body}\n`);
  if (next !== text) {
    writeFileSync(mocFile, next, 'utf8');
    return true;
  }
  return false;
}

const areas = AREAS.filter((a) => !onlyArea || a.area === onlyArea);
let drillsWritten = 0;
let problemsPooled = 0;
let mocsUpdated = 0;

for (const area of areas) {
  // collect problems from every payload in the area
  const pool = [];
  const trapPool = [];
  const sources = [];

  for (const t of area.topics) {
    const p = payloadPath(t);
    if (!existsSync(p)) continue;
    let pl;
    try {
      pl = JSON.parse(readFileSync(p, 'utf8').replace(/^\uFEFF/, ''));
    } catch {
      continue; // validation is build-notes' job; skip unparseable files here
    }
    const label = `${t.id} ${t.title}`;
    let used = 0;
    for (const prob of pl.problems ?? []) {
      if (!prob?.prompt || !prob?.ans) continue;
      pool.push({ ...prob, source: t.id, sourceTitle: t.title, sourceArea: area.area });
      used++;
    }
    for (const tr of pl.traps ?? []) {
      trapPool.push({ text: tr, source: t.id, sourceTitle: t.title });
    }
    if (used) sources.push({ id: t.id, title: t.title, n: used });
  }

  if (!pool.length) continue;
  problemsPooled += pool.length;

  const rand = rng(seed + area.area.length * 7919);
  const picked = shuffle(pool, rand).slice(0, Math.min(perDrill, pool.length));
  const areaLabel = area.area.replace(/^\d+_/, '').replace(/_/g, ' ');

  // ---- main drill --------------------------------------------------------
  const body = picked
    .map((p, i) => {
      const parts = [`### ${i + 1}. ${p.prompt}`];
      if (p.give?.length) parts.push(`**Given:** ${p.give.join('; ')}`);
      parts.push(`> [!success]- Answer\n> **${p.ans}**`);
      if (p.trap) parts.push(`> [!warning] Trap\n> ${p.trap}`);
      parts.push(`<sub>from ${p.source}</sub>`);
      return parts.join('\n\n');
    })
    .join('\n\n');

  const srcTable = sources.map((s) => `| ${s.id} | ${s.title} | ${s.n} |`).join('\n');

  const drill = `---
title: "${areaLabel} — Drill"
type: drill
area: ${area.area}
part: ${area.part}
seed: ${seed}
count: ${picked.length}
pool: ${pool.length}
updated: ${today}
---

# ${areaLabel} — Practice Drill

**${picked.length} problems** drawn from a pool of ${pool.length} across ${sources.length} topics.
Deterministically shuffled with seed \`${seed}\` — regenerate with
\`node build/build-drills.mjs --area ${area.area} --seed ${seed}\`.

> [!question] How to use this
> Answer first, on paper. Only then expand the answer callout. Any problem whose trap
> you hit goes on the revisit list — the trap is the whole reason the problem exists.

---

${body}

---

## Sources in this drill

| ID | Topic | Problems available |
| --- | --- | --- |
${srcTable}

Generated by \`build/build-drills.mjs\` from the problem records in the topic payloads.
Do not hand-edit: change the source payload and regenerate.
`;

  write(join(VAULT, area.part, area.area, 'Sets', `${area.area.replace(/^\d+_/, '')}_Drill.md`), drill);
  drillsWritten++;

  const setsDir = join(VAULT, area.part, area.area, 'Sets');
  const mocFile = join(VAULT, area.part, area.area, `${area.moc}.md`);
  const setFiles = readdirSync(setsDir).filter((f) => f.endsWith('.md')).sort();
  if (linkSetsIntoMOC(setsDir, mocFile, setFiles)) mocsUpdated++;

  // ---- traps-only recall drill -------------------------------------------
  if (includeTraps && trapPool.length) {
    const tPicked = shuffle(trapPool, rand).slice(0, Math.min(12, trapPool.length));
    const tBody = tPicked
      .map((t, i) => {
        // A trap is a statement of a failure mode. Ask the student to name the rule
        // it violates — the trap text itself is the answer.
        const lead = t.text.split(/\.\s/)[0].replace(/^\*\*|\*\*$/g, '');
        return `### ${i + 1}. What goes wrong here?\n\n> [!success]- Trap\n> ${t.text}\n\n<sub>from ${t.source}</sub>`;
      })
      .join('\n\n');

    const traps = `---
title: "${areaLabel} — Trap Recall"
type: drill
area: ${area.area}
part: ${area.part}
mode: traps-only
count: ${tPicked.length}
updated: ${today}
---

# ${areaLabel} — Trap Recall

**${tPicked.length} traps** from this area's notes. Read each and say aloud what the
student actually did wrong before expanding it.

---

${tBody}

---

Generated by \`build/build-drills.mjs --include-traps\`.
`;
    write(join(VAULT, area.part, area.area, 'Sets', `${area.area.replace(/^\d+_/, '')}_Traps.md`), traps);
    drillsWritten++;
  }
}

console.log(`areas scanned:   ${areas.length}`);
console.log(`drills written:  ${drillsWritten}`);
console.log(`problems pooled: ${problemsPooled}`);
console.log(`MOCs updated:    ${mocsUpdated}`);
console.log(`per drill:       ${perDrill}   seed: ${seed}`);
